"""The engine's message handlers as named hook points:
src/dao/generated/MessageHandlers.h.

The engine's classes answer messages (dev/MESSAGE_HANDLERS.md): each
handler is a member function `bool Owner::HandleMessage(const Message &)`
that one class runs for one message class, and tools/message_handlers.py
lists the 314 the exe builds, dev/message_handlers.csv. This names each
non-trivial one (a trivial one is a stub the compiler shares between many)
as an address a plugin can detour with dao::messages::HandlerFn, and lists
them all in a table with their owner and message.

Whether a handler takes the one argument its shape says is read from its
end here: `ret 4` (281 of 308 on 2026-09-30) confirms it; a handler that
ends by jumping into another function cannot be read that way and is
marked unconfirmed.

    python tools/gen_message_handlers.py            rewrite the header
    python tools/gen_message_handlers.py --check    exit 1 if it is stale;
                                                    0 with a note when there is no exe copy
"""

import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import address_ids  # noqa: E402
import daoexe  # noqa: E402

ROOT = os.path.join(HERE, "..")
TABLE = os.path.join(ROOT, "dev", "message_handlers.csv")
OUT = os.path.join(ROOT, "src", "dao", "generated", "MessageHandlers.h")


def confirmed(img, va):
    ins = img.disasm(va, None, limit=0x4000)
    return bool(ins) and ins[-1].mnemonic == "ret" and ins[-1].op_str in ("4", "0x4")


def identifier(owner, message):
    return re.sub(r"\W", "_", (owner + "_" + message).replace("::", "_"))


def header(rows, img):
    ids, _ = address_ids.table()
    lines = [
        "// Generated by tools/gen_message_handlers.py from dev/message_handlers.csv. Do not",
        "// edit: run the generator again.",
        "//",
        "// Each engine class's handler for each message it answers, as an ID to",
        "// detour (dao/Addresses.h; the address beside each is where the GOG build's",
        "// listing has it): `bool __thiscall Owner::HandleMessage(const Message &)`,",
        "// written HandlerFn here. `confirmed` says its `ret 4` was read; the rest",
        "// end in a jump and are taken on the shape the others share.",
        "//",
        "// clang-format off",
        "#pragma once",
        "",
        '#include "dao/Addresses.h"',
        "",
        "#include <cstdint>",
        "",
        "namespace dao::messages",
        "{",
        "",
        "// A handler as the engine calls it; __fastcall so ecx, the owner, arrives",
        "// as the engine sends it. True if the message was handled.",
        "using HandlerFn = bool(__fastcall *)(void *owner, int edx, const void *message);",
        "",
        "struct Handler",
        "{",
        "    const char *owner;",
        "    const char *message;",
        "    AddressId id;             // the function, as dao/Addresses.h has them",
        "    std::uintptr_t address;   // where the GOG build's listing has it",
        "    std::int32_t thisAdjust;  // added to the owner's address before the call",
        "    bool trivial;             // a stub the compiler shares: its calls say nothing",
        "    bool confirmed;           // ret 4 read at its end",
        "};",
        "",
        "namespace handler",
        "{",
        "",
    ]
    table = []
    names = {}
    for r in rows:
        va = int(r["function_va"], 16)
        trivial = r["trivial"] == "1"
        ok = not trivial and confirmed(img, va)
        table.append(
            (r["owner"], r["message"], va, int(r["this_adjust"] or 0), trivial, ok)
        )
        if trivial:
            continue
        name = identifier(r["owner"], r["message"])
        if name in names:
            continue
        names[name] = va
        lines.append(
            f"inline constexpr AddressId {name}{{{ids.get(va, 0)}}}; // {va:#010x}"
            + ("" if ok else ", not confirmed")
        )
    lines += [
        "",
        "} // namespace handler",
        "",
        "inline constexpr Handler kHandlers[] = {",
    ]
    for owner, message, va, adjust, trivial, ok in table:
        lines.append(
            f'    {{"{owner}", "{message}", AddressId{{{ids.get(va, 0)}}}, {va:#010x}, {adjust}, {str(trivial).lower()}, {str(ok).lower()}}},'
        )
    lines += ["};", "", "} // namespace dao::messages", "", "// clang-format on", ""]
    return "\n".join(lines), len(names)


def main(argv):
    if not os.path.exists(daoexe.EXE):
        if "--check" in argv:
            print("gen_message_handlers: no game/DAOrigins.exe, nothing to check")
            return 0
        print("no game/DAOrigins.exe", file=sys.stderr)
        return 2
    with open(TABLE, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    text, named = header(rows, daoexe.Image())
    if "--check" in argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                have = f.read()
        except FileNotFoundError:
            have = ""
        if "".join(have.split()) != "".join(text.split()):
            print(
                f"gen_message_handlers: {os.path.normpath(OUT)} is stale; run tools/gen_message_handlers.py"
            )
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{len(rows)} handlers, {named} named")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
