"""Write src/dao/generated/ScriptFields.h from the harvested fields.

Every field a script command returns (dev/script_fields.csv, from
tools/script_fields.py), whose command takes one object and returns an int
or an object (dev/script_commands.csv, from script.ldf), becomes a typed
field descriptor, `dao::generated::CCCreature_PackageAI`, which the classes
in dao/Objects.h wrap with natural names; and an entry in kScriptGetters,
which the probe uses to check each field against the engine's own answer
in play (src/plugins/probe/ScriptChecks.cpp).

The header is checked in, so the library builds without Python; ctest runs
this with --check, which fails if the header is not what the tables give.

    python tools/gen_script_fields.py            rewrite the header
    python tools/gen_script_fields.py --check    fail if it would change
"""

import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
FIELDS = os.path.join(ROOT, "dev", "script_fields.csv")
COMMANDS = os.path.join(ROOT, "dev", "script_commands.csv")
OUT = os.path.join(ROOT, "src", "dao", "generated", "ScriptFields.h")

CLASSES = ("CCObject", "CCCreature", "CCPlaceable", "CCWayPoint")
MAX_DEPTH = 3


def cpp_type(script_type, width):
    """The C++ type a field is read as: what the instruction read, typed by
    what the script gets."""
    if script_type == "object":
        return "ObjectId"
    return {4: "std::int32_t", 2: "std::uint16_t", 1: "std::uint8_t"}[width]


def accessor(command):
    """GetPackageAI -> PackageAI: the field's name in the descriptor."""
    return command[3:] if command.startswith("Get") else command


def getters():
    """[(class, offsets, width, script type, command id, command name)] for
    the fields a one-object getter returns, in table order."""
    signatures = {}
    with open(COMMANDS, encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            if row["script_name"]:
                signatures[row["script_name"]] = (int(row["id"]), row["signature"])
    out = []
    with open(FIELDS, encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            if not row["returned_by"] or row["class"] not in CLASSES:
                continue
            widths = row["width"].split("/")
            if len(widths) != 1:
                continue  # read at more than one width: not one field
            width = int(widths[0])
            offsets = [int(p.lstrip("+"), 16) for p in row["path"].split()]
            if len(offsets) > MAX_DEPTH:
                continue
            for command in row["returned_by"].split(" | "):
                if command not in signatures:
                    continue
                cid, signature = signatures[command]
                m = re.fullmatch(r"(int|object) \w+\(object \w+\)", signature)
                if not m:
                    continue  # the probe's check pops one object and pushes one int or object
                out.append((row["class"], offsets, width, m.group(1), cid, command))
    return out


def render(rows):
    lines = [
        "// Generated by tools/gen_script_fields.py from dev/script_fields.csv and",
        "// dev/script_commands.csv. Do not edit: edit the tables, or the tools that",
        "// harvest them (tools/script_fields.py), and run the generator again.",
        "//",
        "// Each field a script command returns, found by following the command's",
        '// body (dev/SCRIPT_COMMANDS.md, "Fields"), typed by what the script gets',
        "// and by the width the engine reads. dao/Objects.h gives them natural",
        "// names; the probe checks each against the engine's own answer in play.",
        "#pragma once",
        "",
        '#include "dao/Field.h"',
        '#include "dao/ObjectId.h"',
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace dao::generated",
        "{",
        "",
    ]
    current = None
    for cls, offsets, width, script_type, cid, command in rows:
        if cls != current:
            lines.append(f"// {cls}")
            current = cls
        path = ", ".join(f"{o:#x}" for o in offsets)
        lines.append(
            f"// {command} (script command {cid}) returns it, as {script_type}."
        )
        lines.append(
            f"inline constexpr Field<{cpp_type(script_type, width)}, {len(offsets)}> "
            f"{cls}_{accessor(command)}{{{{{{{path}}}}}}};"
        )
    lines += [
        "",
        "// The same fields, for the probe to check in play.",
        "enum class ObjectClass : std::uint8_t",
        "{",
        *(f"    {c}," for c in CLASSES),
        "};",
        "",
        "struct ScriptGetter",
        "{",
        "    int command;                            // the script command's number",
        "    const char *name;                       // and its name in script.ldf",
        "    ObjectClass objectClass;                // what its object argument is looked up as",
        "    bool returnsObject;                     // an object id, else an int",
        "    std::uint8_t width;                     // bytes the engine reads",
        "    std::uint8_t depth;                     // offsets used below",
        f"    std::array<std::uint32_t, {MAX_DEPTH}> offsets; // the path",
        "};",
        "",
        "inline constexpr ScriptGetter kScriptGetters[] = {",
    ]
    for cls, offsets, width, script_type, cid, command in rows:
        padded = offsets + [0] * (MAX_DEPTH - len(offsets))
        path = ", ".join(f"{o:#x}" for o in padded)
        returns_object = "true" if script_type == "object" else "false"
        lines.append(
            f'    {{{cid}, "{command}", ObjectClass::{cls}, {returns_object}, {width}, {len(offsets)}, {{{{{path}}}}}}},'
        )
    lines += ["};", "", "} // namespace dao::generated", ""]
    return "\n".join(lines)


def main(argv):
    text = render(getters())
    try:
        with open(OUT, encoding="utf-8") as f:
            current = f.read().replace("\r\n", "\n")
    except FileNotFoundError:
        current = None
    if "--check" in argv:
        if current is None:
            print(
                f"{os.path.normpath(OUT)} is missing; run tools/gen_script_fields.py",
                file=sys.stderr,
            )
            return 1
        # clang-format may have laid the checked-in copy out differently:
        # compare what matters, the tokens.
        if current.split() != text.split():
            print(
                f"{os.path.normpath(OUT)} is out of date; run tools/gen_script_fields.py",
                file=sys.stderr,
            )
            return 1
        print(f"{os.path.normpath(OUT)} is up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(
        f"wrote {os.path.normpath(OUT)}: {text.count('inline constexpr Field<')} fields"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
