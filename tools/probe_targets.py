"""Write the probe's list of functions to count, from the two tables.

    python tools/probe_targets.py <out.inc>

Every implemented script command (dev/script_commands.csv) and every
message handler with a known method (dev/message_handlers.csv), one entry
per address, as C++ initialisers the probe includes:

    {dao::AddressId{12587}, 0x006403C0u, probe::Kind::Handler, "GameModeController::HandleMessage_UserTogglePauseMessage"},

the function's ID (dao/Addresses.h), by which it is found in whatever build
is running, and the address the GOG build's listing has it at, which is how
the probe's reports name it.

An address that implements several commands, or several handlers, gets
one entry whose label names them all, joined by " | ". The build runs this
(CMakeLists.txt) whenever either table or this script changes.
"""

import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import address_ids  # noqa: E402

COMMANDS = os.path.join(HERE, "..", "dev", "script_commands.csv")
HANDLERS = os.path.join(HERE, "..", "dev", "message_handlers.csv")


def targets():
    """{address: (kind, [labels])}, commands first."""
    out = {}
    with open(COMMANDS, encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            va = int(row["function_va"], 16)
            if va:
                out.setdefault(va, ("Command", []))[1].append(row["name"])
    with open(HANDLERS, encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            va = int(row["function_va"], 16)
            if not va or row.get("trivial") == "1":
                continue
            label = f"{row['owner']}::{row['method']}_{row['message'].split('::')[-1]}"
            kind, labels = out.setdefault(va, ("Handler", []))
            labels.append(label)
    return out


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(argv):
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    rows = targets()
    ids, _ = address_ids.table()
    lines = [
        "// Generated by tools/probe_targets.py from dev/script_commands.csv and",
        "// dev/message_handlers.csv. Do not edit; edit the tables.",
    ]
    for va in sorted(rows):
        kind, labels = rows[va]
        lines.append(
            f"{{dao::AddressId{{{ids.get(va, 0)}}}, {va:#010x}u, probe::Kind::{kind}, {c_string(' | '.join(labels))}}},"
        )
    text = "\n".join(lines) + "\n"
    # Rewrite only on a change, so the probe is not rebuilt for nothing.
    try:
        with open(argv[0], encoding="utf-8") as f:
            if f.read() == text:
                return 0
    except FileNotFoundError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(argv[0])), exist_ok=True)
    with open(argv[0], "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{len(rows)} probe targets -> {argv[0]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
